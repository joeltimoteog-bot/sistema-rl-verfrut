--  Esquema "eti" en Supabase: una tabla por coleccion de Firestore de los sistemas
--  Evaluacion ETI y Capacitaciones ETI. Cada fila = un documento, TAL CUAL (jsonb).
--  Solo CREA (IF NOT EXISTS). No borra ni modifica nada existente.
-- ═══════════════════════════════════════════════════════════════════════════
CREATE SCHEMA IF NOT EXISTS eti;

-- mezcla profunda como set(..., {merge:true}) de Firestore
CREATE OR REPLACE FUNCTION eti.mezclar(a jsonb, b jsonb) RETURNS jsonb LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN a IS NULL OR jsonb_typeof(a) <> 'object' OR jsonb_typeof(b) <> 'object' THEN b
    ELSE (SELECT COALESCE(jsonb_object_agg(k, CASE WHEN a ? k AND b ? k THEN eti.mezclar(a -> k, b -> k)
                                                   WHEN b ? k THEN b -> k ELSE a -> k END), '{}'::jsonb)
            FROM (SELECT jsonb_object_keys(a) AS k UNION SELECT jsonb_object_keys(b)) s)
  END
$$;

DO $$
DECLARE c text;
BEGIN
  FOREACH c IN ARRAY ARRAY[
    -- Evaluacion ETI
    'respuestas_qr', 'evaluaciones_conocimiento', 'config_eti', 'sesiones_qr', 'programaciones_eti',
    'programaciones_eval', 'informes_enviados', 'evaluaciones_depuradas', 'banco_historial',
    -- Capacitaciones ETI
    'capacitaciones', 'supervisores_eti', 'usuarios_eti',
    -- _INFORME_ETI_V1 (05-nov): informes INF-SC-GH-03 emitidos (Word + fotos en Storage)
    'informes_eti',
    -- _CAP_INFORME_V1 (05-nov): informes de capacitacion del Sistema RR.LL.
    'informes_cap',
    -- _ENCUESTA_SAT_V1 (05-nov): QR de la encuesta de satisfaccion y respuestas del personal capacitado
    'encuestas_qr', 'encuestas_sat',
    -- _ALERTAS_REF_V1 (06-nov): seguimiento del reforzamiento por ruta y tema (pendiente / reforzado)
    'alertas_ref'
  ] LOOP
    EXECUTE format('CREATE TABLE IF NOT EXISTS eti.%I (
        id          text PRIMARY KEY,
        datos       jsonb NOT NULL DEFAULT ''{}''::jsonb,
        creado      timestamptz NOT NULL DEFAULT now(),
        actualizado timestamptz NOT NULL DEFAULT now(),
        origen      text)', c);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON eti.%I USING gin (datos jsonb_path_ops)', c || '_gin', c);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON eti.%I ((datos->>''fecha''))', c || '_fecha', c);
  END LOOP;
END $$;

