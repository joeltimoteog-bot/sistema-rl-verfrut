CREATE TABLE IF NOT EXISTS eti._bitacora (
  n bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coleccion text NOT NULL, id text NOT NULL, op text NOT NULL,
  usuario text, origen text, en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS _bitacora_en ON eti._bitacora (en);

