CREATE TABLE IF NOT EXISTS rl.cap_eliminados (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_capacitacion extensions.citext NOT NULL,
  eliminado_en timestamp NOT NULL DEFAULT (now() at time zone 'utc'),
  eliminado_por extensions.citext,
  motivo extensions.citext,
  tema extensions.citext,
  fecha_capacitacion extensions.citext,
  empresa extensions.citext,
  total_asistentes integer,
  cabecera extensions.citext,
  asistentes extensions.citext,
  restaurado_en timestamp
);

-- ── KPI: protecciones "inmutables" (equivalen a los TRIGGER de SQL Server de shared/kpi-db.js) ──
CREATE OR REPLACE FUNCTION rl.tr_kpi_alertas_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' OR NEW.mensaje <> OLD.mensaje OR NEW.tipo <> OLD.tipo OR COALESCE(NEW.usuario, '') <> COALESCE(OLD.usuario, '')
     OR NEW.creado <> OLD.creado OR (OLD.enviado IS NOT NULL AND COALESCE(NEW.enviado, '1900-01-01') <> OLD.enviado) THEN
    RAISE EXCEPTION 'La bitacora de alertas KPI no se puede editar ni borrar';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
DROP TRIGGER IF EXISTS tr_kpi_alertas_inmutable ON rl.kpi_alertas;
CREATE TRIGGER tr_kpi_alertas_inmutable BEFORE UPDATE OR DELETE ON rl.kpi_alertas FOR EACH ROW EXECUTE FUNCTION rl.tr_kpi_alertas_inmutable();

CREATE OR REPLACE FUNCTION rl.tr_kpi_cierremes_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Un mes cerrado no se edita ni se borra'; END $$;
DROP TRIGGER IF EXISTS tr_kpi_cierremes_inmutable ON rl.kpi_cierremes;
CREATE TRIGGER tr_kpi_cierremes_inmutable BEFORE UPDATE OR DELETE ON rl.kpi_cierremes FOR EACH ROW EXECUTE FUNCTION rl.tr_kpi_cierremes_inmutable();

CREATE OR REPLACE FUNCTION rl.tr_kpi_notas_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Las notas registradas no se editan ni se borran: registre una nueva'; END $$;
DROP TRIGGER IF EXISTS tr_kpi_notas_inmutable ON rl.kpi_notas;
CREATE TRIGGER tr_kpi_notas_inmutable BEFORE UPDATE OR DELETE ON rl.kpi_notas FOR EACH ROW EXECUTE FUNCTION rl.tr_kpi_notas_inmutable();
