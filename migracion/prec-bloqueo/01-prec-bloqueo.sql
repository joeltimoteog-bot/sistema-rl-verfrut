--   1) Precedentes: columnas nuevas del formulario breve (ruta, codigo, area, motivo atribuido,
--      sector y nombre de quien registra).
--   2) Bloqueo temporal del Registro de Atenciones: tabla nueva rl.at_bloqueos.
