BEGIN;
SET LOCAL search_path TO rl, public, extensions;

ALTER TABLE rl.casos_precedentes ADD COLUMN IF NOT EXISTS ruta           extensions.citext;
ALTER TABLE rl.casos_precedentes ADD COLUMN IF NOT EXISTS cod_trabajador extensions.citext;
ALTER TABLE rl.casos_precedentes ADD COLUMN IF NOT EXISTS area           extensions.citext;
ALTER TABLE rl.casos_precedentes ADD COLUMN IF NOT EXISTS motivo_falta   extensions.citext;
ALTER TABLE rl.casos_precedentes ADD COLUMN IF NOT EXISTS creado_sector  extensions.citext;
ALTER TABLE rl.casos_precedentes ADD COLUMN IF NOT EXISTS creado_nombre  extensions.citext;
CREATE INDEX IF NOT EXISTS ix_casos_precedentes_creado_por ON rl.casos_precedentes (creado_por);
CREATE INDEX IF NOT EXISTS ix_casos_dni ON rl.casos (dni);

CREATE TABLE IF NOT EXISTS rl.at_bloqueos (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  motivo        text        NOT NULL,                 -- 'Cierre de quincena' | 'Cierre de mes' | otro
  desde         timestamptz NOT NULL,
  hasta         timestamptz NOT NULL,
  mensaje       text        NOT NULL,
  creado_por    text        NOT NULL,
  creado        timestamptz NOT NULL DEFAULT now(),
  cancelado     boolean     NOT NULL DEFAULT false,
  cancelado_por text,
  cancelado_en  timestamptz,
  CONSTRAINT ck_at_bloqueos_rango CHECK (hasta > desde AND hasta <= desde + interval '2 hours')
);
CREATE INDEX IF NOT EXISTS ix_at_bloqueos_hasta ON rl.at_bloqueos (hasta) WHERE cancelado = false;
COMMENT ON TABLE rl.at_bloqueos IS 'Bloqueos temporales del Registro de Atenciones (cierre de quincena / de mes). Lo programa el administrador.';
COMMIT;
