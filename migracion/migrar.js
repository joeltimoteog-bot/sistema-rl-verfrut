function req(m) { try { return require(m); } catch (e) { try { return require(path.join(FUNCS, 'node_modules', m)); } catch (e2) { console.error('Falta el paquete "' + m + '". Ejecuta:  npm install   (en la carpeta migracion)'); process.exit(1); } } }
