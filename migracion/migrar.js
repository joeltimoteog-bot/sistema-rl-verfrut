function leerAzure() {
  const f = path.join(FUNCS, 'local.settings.json');
  if (!fs.existsSync(f)) { console.error('No encuentro ' + f); process.exit(1); }
  const v = JSON.parse(fs.readFileSync(f, 'utf8').replace(/^\uFEFF/, '')).Values || {};
  for (const k of ['SQL_SERVER', 'SQL_DATABASE', 'SQL_USER', 'SQL_PASSWORD']) if (!v[k]) { console.error('Falta ' + k + ' en local.settings.json'); process.exit(1); }
  return { server: v.SQL_SERVER, database: v.SQL_DATABASE, user: v.SQL_USER, password: v.SQL_PASSWORD,
           options: { encrypt: true, trustServerCertificate: false, connectTimeout: 60000, requestTimeout: 300000 } };
}
function leerSupabase() {
  const f = path.join(AQUI, '.env');
  const txt = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '';
  const m = txt.match(/^\s*SUPABASE_DB_URL\s*=\s*(\S+)/m);
  if (!m) { console.error('Falta migracion\\.env con SUPABASE_DB_URL=postgresql://...'); process.exit(1); }
  return { connectionString: m[1], ssl: { rejectUnauthorized: false } };
}

const minus = (s) => String(s).toLowerCase();
const ESQUEMA = 'rl';
const q = (s) => '"' + minus(s).replace(/"/g, '""') + '"';

function tipoPg(c) {
  const t = minus(c.tipo), n = c.largo;
  switch (t) {
    case 'int': return 'integer';
    case 'bigint': return 'bigint';
    case 'smallint': case 'tinyint': case 'bit': return 'smallint';
    case 'decimal': case 'numeric': return 'numeric(' + c.prec + ',' + c.escala + ')';
    case 'money': case 'smallmoney': return 'numeric(19,4)';
    case 'float': return 'double precision';
    case 'real': return 'real';
    /* textos: citext = sin distinguir mayúsculas, igual que SQL Server (usuario "JTimoteo" = "jtimoteo") */
    case 'nvarchar': case 'varchar': case 'nchar': case 'char': case 'ntext': case 'text': case 'sysname': return 'extensions.citext';
    case 'xml': return 'text';
    case 'datetime': case 'datetime2': case 'smalldatetime': return 'timestamp';
    case 'datetimeoffset': return 'timestamptz';
    case 'date': return 'date';
    case 'time': return 'time';
    case 'uniqueidentifier': return 'uuid';
    case 'varbinary': case 'binary': case 'image': case 'timestamp': case 'rowversion': return 'bytea';
    default: return 'text';
  }
}
function defaultPg(c) {
  if (!c.def) return null;
  let d = String(c.def).trim();
  while (/^\(.*\)$/.test(d)) d = d.slice(1, -1).trim();
  const l = minus(d);
  if (/^(getdate|sysdatetime|sysutcdatetime|getutcdate|current_timestamp)(\(\))?$/.test(l)) return /utc/.test(l) ? "(now() at time zone 'utc')" : 'now()';
  if (/^newid\(\)$/.test(l) || /^newsequentialid\(\)$/.test(l)) return 'gen_random_uuid()';
  if (/^-?\d+(\.\d+)?$/.test(d)) return d;
  const s = d.match(/^N?'([\s\S]*)'$/); if (s) return "'" + s[1] + "'";
  if (/^cast\(getdate\(\) as date\)$/.test(l) || /^convert\(\s*date\s*,\s*getdate\(\)\s*\)$/.test(l)) return 'current_date';
  return null;   /* default no traducible: se omite (se avisa) */
}

async function leerEsquema(az) {
  const r = await az.request().query(`
    SELECT t.name AS tabla, c.name AS col, ty.name AS tipo,
           CASE WHEN ty.name IN ('nvarchar','nchar') AND c.max_length > 0 THEN c.max_length/2 ELSE c.max_length END AS largo,
           c.precision AS prec, c.scale AS escala, c.is_nullable AS nulo, c.is_identity AS ident,
           OBJECT_DEFINITION(c.default_object_id) AS def, c.column_id AS orden, c.is_computed AS calc
    FROM sys.tables t JOIN sys.schemas s ON s.schema_id = t.schema_id
    JOIN sys.columns c ON c.object_id = t.object_id JOIN sys.types ty ON ty.user_type_id = c.user_type_id
    WHERE s.name = 'dbo' AND t.is_ms_shipped = 0 ORDER BY t.name, c.column_id`);
  const idx = await az.request().query(`
    SELECT t.name AS tabla, i.name AS indice, i.is_primary_key AS pk, i.is_unique AS uq,
           STRING_AGG(c.name, ',') WITHIN GROUP (ORDER BY ic.key_ordinal) AS cols
    FROM sys.indexes i JOIN sys.tables t ON t.object_id = i.object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
    JOIN sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id AND ic.is_included_column = 0
    JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
    WHERE s.name = 'dbo' AND i.type > 0 AND t.is_ms_shipped = 0
    GROUP BY t.name, i.name, i.is_primary_key, i.is_unique`);
  const tablas = {};
  for (const c of r.recordset) {
    const t = tablas[c.tabla] || (tablas[c.tabla] = { nombre: c.tabla, columnas: [], indices: [] });
    t.columnas.push(c);
  }
  for (const i of idx.recordset) if (tablas[i.tabla]) tablas[i.tabla].indices.push(i);
  return Object.values(tablas);
}

function ddl(tablas) {
  const out = [], avisos = [];
  for (const t of tablas) {
    const cols = t.columnas.filter(c => !c.calc).map(c => {
      let s = '  ' + q(c.col) + ' ' + tipoPg(c);
      if (c.ident) s += ' GENERATED BY DEFAULT AS IDENTITY';
      else { const d = defaultPg(c); if (d) s += ' DEFAULT ' + d; else if (c.def) avisos.push(t.nombre + '.' + c.col + ': default no traducido ' + c.def); }
      if (!c.nulo) s += ' NOT NULL';
      return s;
    });
    t.columnas.filter(c => c.calc).forEach(c => avisos.push(t.nombre + '.' + c.col + ': columna calculada omitida'));
    const pk = t.indices.find(i => i.pk);
    if (pk) cols.push('  PRIMARY KEY (' + pk.cols.split(',').map(q).join(', ') + ')');
    out.push('CREATE TABLE IF NOT EXISTS ' + q(t.nombre) + ' (\n' + cols.join(',\n') + '\n);');
    for (const i of t.indices.filter(i => !i.pk)) {
      const nom = minus('ix_' + t.nombre + '_' + i.indice).replace(/[^a-z0-9_]/g, '_').slice(0, 60);
      out.push('CREATE ' + (i.uq ? 'UNIQUE ' : '') + 'INDEX IF NOT EXISTS ' + q(nom) + ' ON ' + q(t.nombre) + ' (' + i.cols.split(',').map(q).join(', ') + ');');
    }
  }
  return { sql: out.join('\n\n'), avisos };
}

function guardarEsquemaJson(tablas) {
  const bits = {}, ident = {}, orig = {};
  for (const t of tablas) for (const c of t.columnas) {
    if (minus(c.tipo) === 'bit') (bits[minus(t.nombre)] = bits[minus(t.nombre)] || []).push(minus(c.col));
    if (c.ident) ident[minus(t.nombre)] = minus(c.col);
    if (c.col !== minus(c.col)) orig[minus(c.col)] = c.col;   /* columnas con mayúsculas: se devuelven con su nombre original */
  }
  const j = JSON.stringify({ generado: new Date().toISOString(), columnasBit: bits, identidades: ident, columnasOriginales: orig, tablas: tablas.map(t => t.nombre) }, null, 1);
  fs.writeFileSync(path.join(AQUI, 'esquema.json'), j);
  /* la capa de conexión de las funciones lo usa para devolver bits como true/false y nombres originales */
  fs.writeFileSync(path.join(FUNCS, 'shared', 'esquema-pg.json'), j);
}

async function pasoEsquema(az, pg) {
  /* seguridad: si el esquema destino ya tiene tablas (de otro intento), no se mezcla nada */
  const ya = await pg.query("SELECT COUNT(*) AS n, string_agg(table_name, ', ') AS t FROM information_schema.tables WHERE table_schema = $1", [ESQUEMA]);
  if (Number(ya.rows[0].n) > 0 && !process.argv.includes('--continuar')) {
    throw new Error('El esquema "' + ESQUEMA + '" de Supabase ya tiene ' + ya.rows[0].n + ' tablas (' + String(ya.rows[0].t).slice(0, 200) + '). No se tocó nada. Avísale a Claude.');
  }
  const tablas = await leerEsquema(az);
  const { sql, avisos } = ddl(tablas);
  fs.writeFileSync(path.join(AQUI, 'esquema-supabase.sql'), sql);
  guardarEsquemaJson(tablas);
  await pg.query(sql);
  /* tablas que las funciones crean al primer uso y que aún no existían en Azure */
  const comp = path.join(AQUI, 'complementos.sql');
  if (fs.existsSync(comp)) { await pg.query(fs.readFileSync(comp, 'utf8')); console.log('✅ Complementos aplicados (complementos.sql)'); }
  console.log('✅ Esquema creado en Supabase: ' + tablas.length + ' tablas (copia en esquema-supabase.sql)');
  if (avisos.length) { console.log('⚠️  Avisos (' + avisos.length + '):'); avisos.forEach(a => console.log('   - ' + a)); }
  return tablas;
}

function valorPg(v, tipo) {
  if (v === null || v === undefined) return null;
  const t = minus(tipo);
  if (t === 'bit') return v ? 1 : 0;
  if (v instanceof Date) {
    if (t === 'date') return v.toISOString().slice(0, 10);
    if (t === 'time') return v.toISOString().slice(11, 23);
    return v.toISOString().replace('T', ' ').replace('Z', '');   /* mssql entrega la hora tal cual guardada (UTC) */
  }
  if (Buffer.isBuffer(v)) return v;
  return v;
}

async function pasoDatos(az, pg, tablas) {
  tablas = tablas || await leerEsquema(az);
  for (const t of tablas) {
    const cols = t.columnas.filter(c => !c.calc);
    /* se lee la tabla completa de una vez (sin paginar): así no se salta ni repite ninguna fila */
    const r = await az.request().query('SELECT ' + cols.map(c => '[' + c.col + ']').join(', ') + ' FROM dbo.[' + t.nombre + ']');
    const filas = r.recordset;
    await pg.query('BEGIN');
    try {
      await pg.query('TRUNCATE ' + q(t.nombre));
      /* Postgres admite hasta 65535 parámetros por consulta */
      const porConsulta = Math.max(1, Math.min(1000, Math.floor(60000 / cols.length)));
      for (let k = 0; k < filas.length; k += porConsulta) {
        const sub = filas.slice(k, k + porConsulta), vals = [];
        const tuplas = sub.map((row, i) => { cols.forEach(c => vals.push(valorPg(row[c.col], c.tipo))); return '(' + cols.map((c, j) => '$' + (i * cols.length + j + 1)).join(',') + ')'; });
        await pg.query('INSERT INTO ' + q(t.nombre) + ' (' + cols.map(c => q(c.col)).join(', ') + ') OVERRIDING SYSTEM VALUE VALUES ' + tuplas.join(','), vals);
        process.stdout.write('\r   ' + t.nombre + ': ' + Math.min(k + porConsulta, filas.length) + ' / ' + filas.length);
      }
      const id = cols.find(c => c.ident);
      if (id) await pg.query("SELECT setval(pg_get_serial_sequence('" + minus(t.nombre) + "', '" + minus(id.col) + "'), COALESCE((SELECT MAX(" + q(id.col) + ') FROM ' + q(t.nombre) + '), 0) + 1, false)');
      await pg.query('COMMIT');
    } catch (e) { await pg.query('ROLLBACK').catch(() => {}); throw new Error(t.nombre + ': ' + e.message); }
    process.stdout.write('\r✅ ' + t.nombre + ': ' + filas.length + ' filas' + ' '.repeat(20) + '\n');
  }
}


/* ── corte: reservar ids antes de pasar a Supabase, y luego traer lo que se registró en Azure durante el cambio ── */
const RESERVA = 1000;
async function pasoReservar(az, pg) {
  const tablas = await leerEsquema(az); const est = { fecha: new Date().toISOString(), tablas: {} };
  for (const t of tablas) {
    const id = t.columnas.find(c => c.ident); if (!id) continue;
    const ma = Number((await az.request().query('SELECT ISNULL(MAX([' + id.col + ']), 0) AS m FROM dbo.[' + t.nombre + ']')).recordset[0].m);
    const ms = Number((await pg.query('SELECT COALESCE(MAX(' + q(id.col) + '), 0) AS m FROM ' + q(t.nombre))).rows[0].m);
    const desde = Math.max(ma, ms) + RESERVA;
    await pg.query("SELECT setval(pg_get_serial_sequence('" + minus(t.nombre) + "', '" + minus(id.col) + "'), " + desde + ', false)');
    est.tablas[t.nombre] = { col: id.col, copiadoHasta: ms, nuevosDesde: desde };
  }
  fs.writeFileSync(path.join(AQUI, 'estado-corte.json'), JSON.stringify(est, null, 1));
  console.log('✅ Ids reservados: lo nuevo en Supabase empieza ' + RESERVA + ' números después de lo último de Azure (estado-corte.json)');
}
async function pasoPendientes(az, pg) {
  const f = path.join(AQUI, 'estado-corte.json');
  if (!fs.existsSync(f)) throw new Error('Falta estado-corte.json: ejecuta antes "node migrar.js reservar"');
  const est = JSON.parse(fs.readFileSync(f, 'utf8')), desde = new Date(new Date(est.fecha).getTime() - 30 * 60000);
  const tablas = await leerEsquema(az); const T = n => tablas.find(t => t.nombre.toLowerCase() === n.toLowerCase());
  let total = 0;
  /* 1) Atenciones nuevas en Azure (id mayor a lo copiado y menor a la reserva) */
  const at = T('Atenciones'), e = est.tablas[at.nombre];
  if (e) {
    const cols = at.columnas.filter(c => !c.calc);
    const r = await az.request().input('d', mssql.Int, e.copiadoHasta).input('h', mssql.Int, e.nuevosDesde).query('SELECT ' + cols.map(c => '[' + c.col + ']').join(', ') + ' FROM dbo.[' + at.nombre + '] WHERE [' + e.col + '] > @d AND [' + e.col + '] < @h');
    for (const row of r.recordset) {
      const v = cols.map(c => valorPg(row[c.col], c.tipo));
      const x = await pg.query('INSERT INTO ' + q(at.nombre) + ' (' + cols.map(c => q(c.col)).join(', ') + ') OVERRIDING SYSTEM VALUE VALUES (' + cols.map((c, i) => '$' + (i + 1)).join(',') + ') ON CONFLICT DO NOTHING', v);
      total += x.rowCount;
    }
    console.log('✅ Atenciones registradas en Azure durante el cambio: ' + r.recordset.length + ' (copiadas ' + total + ')');
  }
  /* 2) huellas de doble clic, KPI de registro y contador del N° */
  for (const [nom, claveSql] of [['AtIdem', 'clave'], ['KPI_AtRegistro', 'anio, nro']]) {
    const t = T(nom); if (!t) continue; const cols = t.columnas.filter(c => !c.calc);
    const fechaCol = cols.find(c => /^(creado|fecha_registro)$/i.test(c.col));
    const r = await az.request().input('f', mssql.DateTime2, desde).query('SELECT ' + cols.map(c => '[' + c.col + ']').join(', ') + ' FROM dbo.[' + t.nombre + ']' + (fechaCol ? ' WHERE [' + fechaCol.col + '] >= @f' : ''));
    let n = 0;
    for (const row of r.recordset) {
      const keys = claveSql.split(',').map(k => k.trim());
      const ya = await pg.query('SELECT 1 FROM ' + q(t.nombre) + ' WHERE ' + keys.map((k, i) => q(k) + ' = $' + (i + 1)).join(' AND '), keys.map(k => row[cols.find(c => c.col.toLowerCase() === k).col]));
      if (ya.rowCount) continue;
      await pg.query('INSERT INTO ' + q(t.nombre) + ' (' + cols.map(c => q(c.col)).join(', ') + ') OVERRIDING SYSTEM VALUE VALUES (' + cols.map((c, i) => '$' + (i + 1)).join(',') + ')', cols.map(c => valorPg(row[c.col], c.tipo)));
      n++;
    }
    console.log('✅ ' + t.nombre + ': ' + n + ' registros nuevos copiados');
  }
  await pg.query('UPDATE atnrocontador s SET ultimo = GREATEST(s.ultimo, COALESCE((SELECT MAX(nro) FROM atenciones a WHERE a.anio = s.anio), 0))');
  const dup = await pg.query('SELECT anio, nro, COUNT(*) AS n FROM atenciones WHERE anio >= 2026 GROUP BY anio, nro HAVING COUNT(*) > 1 AND COUNT(DISTINCT dni) > 1');
  console.log(dup.rowCount ? '⚠️ N° repetidos con distinto DNI (avísale a Claude): ' + JSON.stringify(dup.rows) : '✅ Sin N° de atención repetidos');
}

async function pasoVerificar(az, pg, tablas) {
  tablas = tablas || await leerEsquema(az);
  let malas = 0;
  console.log('\nTABLA'.padEnd(34) + 'AZURE'.padStart(10) + 'SUPABASE'.padStart(10));
  for (const t of tablas) {
    const a = Number((await az.request().query('SELECT COUNT_BIG(*) AS n FROM dbo.[' + t.nombre + ']')).recordset[0].n);
    let s = -1; try { s = Number((await pg.query('SELECT COUNT(*) AS n FROM ' + q(t.nombre))).rows[0].n); } catch (e) {}
    const ok = a === s; if (!ok) malas++;
    console.log((ok ? '✅ ' : '❌ ') + t.nombre.padEnd(31) + String(a).padStart(10) + String(s).padStart(10));
  }
  console.log(malas ? '\n❌ ' + malas + ' tabla(s) con diferencias' : '\n✅ TODAS LAS TABLAS COINCIDEN');
  return malas;
}

