/* ═══════════════════════════════════════════════════════════════════════════
   migracion/migrar.js — Azure SQL (sistema-rl-db) → Supabase PostgreSQL
   _MIGRA_SUPABASE_V1 (05-nov-2026)

   NO MODIFICA AZURE: solo lee de Azure y escribe en Supabase.

   Uso (en C:\sistema-rl-verfrut\migracion):
     node migrar.js esquema     → lee las tablas de Azure y crea las mismas en Supabase
     node migrar.js datos       → copia todas las filas (borra antes lo que haya en Supabase)
     node migrar.js verificar   → compara el número de filas tabla por tabla
     node migrar.js todo        → esquema + datos + verificar

   Credenciales:
     · Azure: las mismas de azure\functions\local.settings.json (SQL_SERVER, SQL_DATABASE, SQL_USER, SQL_PASSWORD)
     · Supabase: archivo migracion\.env con una línea
         SUPABASE_DB_URL=postgresql://postgres.xxxx:CONTRASEÑA@aws-0-sa-east-1.pooler.supabase.com:5432/postgres
       (Supabase → Project Settings → Database → Connection string → "Session pooler")

   Reglas de conversión (para que las funciones sigan funcionando igual):
     · nombres de tablas y columnas en minúsculas (Postgres no distingue mayúsculas si no se usan comillas)
     · bit → smallint (las consultas "activo = 1" siguen valiendo); la lista de columnas bit se guarda en
       esquema.json para que la capa de conexión las devuelva como true/false, igual que mssql
     · identity → GENERATED BY DEFAULT AS IDENTITY (se conservan los id originales y luego se ajusta el contador)
     · nvarchar(max) / ntext → text · datetime/datetime2 → timestamp · uniqueidentifier → uuid
   ═══════════════════════════════════════════════════════════════════════════ */
