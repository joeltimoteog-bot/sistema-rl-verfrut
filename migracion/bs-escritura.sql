/* Auditoría inmutable: mientras bs_fuente diga 'supabase' para bs_auditoria, UPDATE/DELETE/TRUNCATE fallan.
   (Antes del cambio de fuente la hoja de Google todavía la reemplaza completa, por eso la regla es dinámica.) */
CREATE OR REPLACE FUNCTION bs_auditoria_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE f text;
BEGIN
  SELECT fuente INTO f FROM bs_fuente WHERE clave = 'bs_auditoria';
  IF f = 'supabase' THEN RAISE EXCEPTION 'bs_auditoria es inmutable: no se puede % una fila de auditoría', TG_OP; END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  IF TG_OP = 'TRUNCATE' THEN RETURN NULL; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS bs_auditoria_inmutable_fila ON "bs_auditoria";
CREATE TRIGGER bs_auditoria_inmutable_fila BEFORE UPDATE OR DELETE ON "bs_auditoria" FOR EACH ROW EXECUTE FUNCTION bs_auditoria_inmutable();
DROP TRIGGER IF EXISTS bs_auditoria_inmutable_tabla ON "bs_auditoria";
CREATE TRIGGER bs_auditoria_inmutable_tabla BEFORE TRUNCATE ON "bs_auditoria" FOR EACH STATEMENT EXECUTE FUNCTION bs_auditoria_inmutable();
